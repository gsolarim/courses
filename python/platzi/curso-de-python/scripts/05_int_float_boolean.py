# int
x = 10
print(type(x))

# float
y = 5.678
print(type(y))

# exp
z = 1.2E6
w = 1.2e6
print(z)
print(type(z))
print(w)
print(type(w))
z = 1.2E-6
w = 1.2e-6
print(f"{z:.7f}")
print(type(z))
print(f"{w:.7f}")
print(type(w))

# operaciones matemáticas
print(x + x) # int + int = int
print(x + y) # int + float = float
print(y + y) # float + float = float

# boolean
is_true = True
is_false = False
print(is_true)
print(is_false)
print(type(is_true))
print(type(is_false))